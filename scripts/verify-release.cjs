const fs=require('node:fs');
const asar=require('@electron/asar');
const crypto=require('node:crypto');
const path=require('node:path');
const version=require('../package.json').version;
const root=process.argv[2];if(!root)throw Error('Provide build output directory');
const archive=root+'/win-unpacked/resources/app.asar';
const pkg=JSON.parse(asar.extractFile(archive,'package.json').toString());
const main=asar.extractFile(archive,'electron/main.cjs').toString();
const html=asar.extractFile(archive,'dist/index.html').toString();
const script=html.match(/src="\.\/([^"]+\.js)"/)[1];
const js=asar.extractFile(archive,path.join('dist',...script.split('/'))).toString();
const ico=fs.readFileSync('assets/app.ico');const last=6+16*(ico.readUInt16LE(4)-1);
const png=ico.subarray(ico.readUInt32LE(last+12),ico.readUInt32LE(last+12)+ico.readUInt32LE(last+8));
const file=root+'/云图工作台-'+version+'-x64.exe';const executable=fs.readFileSync(file);
const checks={version:pkg.version,customFrame:main.includes('frame:false'),titlebar:js.includes('desktop-titlebar'),backupStore:asar.extractFile(archive,'electron/manifest.cjs').length>0,hashCancel:asar.extractFile(archive,'electron/hash.cjs').length>0,iconEmbedded:executable.includes(png),bytes:executable.length,sha256:crypto.createHash('sha256').update(executable).digest('hex')};
if(Object.values(checks).some(x=>x===false)||pkg.version!==version)throw Error('Package verification failed');
fs.copyFileSync(file,'../云图工作台安装包/云图工作台-'+version+'-x64.exe');
fs.writeFileSync('../云图工作台安装包/'+version+'构建校验.json',JSON.stringify(checks,null,2));
console.log(JSON.stringify(checks));
